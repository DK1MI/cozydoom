#!/usr/bin/env python3
"""Regenerate ../data.js from tools/doom_info.json (Doom II info tables)."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
D = json.load(open(os.path.join(HERE, 'doom_info.json')))
T, S = D['things'], D['states']

# key, display name, GZDoom class, MBF21 behaviour bits (no boss bits), boss bits, drop item
MONSTERS = [
    ('MT_POSSESSED', 'Zombieman',         'ZombieMan',        '', '', 'Clip'),
    ('MT_SHOTGUY',   'Shotgun Guy',       'ShotgunGuy',       '', '', 'Shotgun'),
    ('MT_CHAINGUY',  'Heavy Weapon Dude', 'ChaingunGuy',      '', '', 'Chaingun'),
    ('MT_WOLFSS',    'Wolfenstein SS',    'WolfensteinSS',    '', '', 'Clip'),
    ('MT_TROOP',     'Imp',               'DoomImp',          '', '', ''),
    ('MT_SERGEANT',  'Demon',             'Demon',            '', '', ''),
    ('MT_SHADOWS',   'Spectre',           'Spectre',          '', '', ''),
    ('MT_SKULL',     'Lost Soul',         'LostSoul',         'RANGEHALF', '', ''),
    ('MT_HEAD',      'Cacodemon',         'Cacodemon',        '', '', ''),
    ('MT_KNIGHT',    'Hell Knight',       'HellKnight',       '', '', ''),
    ('MT_BRUISER',   'Baron of Hell',     'BaronOfHell',      '', 'E1M8BOSS', ''),
    ('MT_UNDEAD',    'Revenant',          'Revenant',         'LONGMELEE+RANGEHALF', '', ''),
    ('MT_FATSO',     'Mancubus',          'Fatso',            '', 'MAP07BOSS1', ''),
    ('MT_BABY',      'Arachnotron',       'Arachnotron',      '', 'MAP07BOSS2', ''),
    ('MT_PAIN',      'Pain Elemental',    'PainElemental',    '', '', ''),
    ('MT_VILE',      'Arch-vile',         'Archvile',         'SHORTMRANGE+DMGIGNORED+NOTHRESHOLD', '', ''),
    ('MT_SPIDER',    'Spider Mastermind', 'SpiderMastermind', 'NORADIUSDMG+RANGEHALF+FULLVOLSOUNDS', 'E3M8BOSS+E4M8BOSS', ''),
    ('MT_CYBORG',    'Cyberdemon',        'Cyberdemon',       'NORADIUSDMG+HIGHERMPROB+RANGEHALF+FULLVOLSOUNDS', 'E2M8BOSS+E4M6BOSS', ''),
]
FIELDS = ['doomednum', 'spawnstate', 'spawnhealth', 'seestate', 'seesound', 'reactiontime',
          'attacksound', 'painstate', 'painchance', 'painsound', 'meleestate', 'missilestate',
          'deathstate', 'xdeathstate', 'deathsound', 'speed', 'radius', 'height', 'mass',
          'damage', 'activesound', 'flags', 'raisestate', 'index']


def chain(i):
    out, seen = [], set()
    while i and i not in seen:
        seen.add(i)
        out.append(i)
        if S[i]['tics'] == -1:
            break
        i = S[i]['next']
    return out


monsters, states = [], {}
for key, name, cls, mbf, boss, drop in MONSTERS:
    m = {f: T[key][f] for f in FIELDS}
    m.update(key=key, name=name, cls=cls, mbf21=mbf, boss=boss, drop=drop)
    for f in ('deathstate', 'xdeathstate'):
        for i in chain(m[f]):
            s = S[i]
            states[i] = {k: s[k] for k in ('sprite', 'frame', 'tics', 'next', 'action')}
    monsters.append(m)

out = ('// Generated by tools/gen_data.py from the Doom II info tables (info.c).\n'
       '// Thing fields use DeHackEd units (fixed point for radius/height).\n'
       'const MONSTERS = ' + json.dumps(monsters, indent=1) + ';\n\n'
       '// Death / gib animation frames of the monsters above (for boss-exit fixes).\n'
       'const STATES = ' + json.dumps({str(k): v for k, v in sorted(states.items())}) + ';\n')
open(os.path.join(HERE, '..', 'data.js'), 'w').write(out)
print('data.js:', len(monsters), 'monsters,', len(states), 'states')

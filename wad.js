// CozyDoom WAD generation: DEHACKED (Boom/MBF21 ports, Crispy, Eternity) plus
// ZSCRIPT + ZMAPINFO (GZDoom/UZDoom). Pure functions, no DOM access.
'use strict';

const BY_KEY = Object.fromEntries(MONSTERS.map(m => [m.key, m]));

// DeHackEd label -> field name (same order as the original DeHackEd editor)
const DEH_FIELDS = [
  ['ID #', 'doomednum'], ['Initial frame', 'spawnstate'], ['Hit points', 'spawnhealth'],
  ['First moving frame', 'seestate'], ['Alert sound', 'seesound'],
  ['Reaction time', 'reactiontime'], ['Attack sound', 'attacksound'],
  ['Injury frame', 'painstate'], ['Pain chance', 'painchance'],
  ['Pain sound', 'painsound'], ['Close attack frame', 'meleestate'],
  ['Far attack frame', 'missilestate'], ['Death frame', 'deathstate'],
  ['Exploding frame', 'xdeathstate'], ['Death sound', 'deathsound'],
  ['Speed', 'speed'], ['Width', 'radius'], ['Height', 'height'], ['Mass', 'mass'],
  ['Missile damage', 'damage'], ['Action sound', 'activesound'], ['Bits', 'flags'],
  ['Respawn frame', 'raisestate'],
];

// First free frame in the DEHEXTRA range (vanilla has 0..966, DEHEXTRA adds 1089+).
const EXTRA_FRAME_BASE = 1100;

function scaledHealth(src, pct) {
  return Math.max(1, Math.round(src.spawnhealth * pct / 100));
}

function deathChain(start) {
  const out = [], seen = new Set();
  let i = start;
  while (i && !seen.has(i)) {
    seen.add(i);
    out.push(i);
    if (STATES[i].tics === -1) break;
    i = STATES[i].next;
  }
  return out;
}

function hasBossDeath(m) {
  return [m.deathstate, m.xdeathstate].some(s => deathChain(s).some(i => STATES[i].action === 'BossDeath'));
}

// A boss-level slot (MAP07, E1M8, ...) whose replacement never calls A_BossDeath
// would leave the level's exit closed, so we patch one in.
function needsBossFix(slot, src) {
  return !!slot.boss && slot.key !== src.key && !hasBossDeath(src);
}

/**
 * choices: { [slotKey]: { src: monsterKey, pct: number } }
 * Returns the list of active changes, in Doom II thing order.
 */
function activeChanges(choices) {
  return MONSTERS.map(slot => {
    const c = choices[slot.key] || { src: slot.key, pct: 100 };
    const src = BY_KEY[c.src];
    return { slot, src, pct: c.pct, hp: scaledHealth(src, c.pct), swapped: src.key !== slot.key };
  }).filter(c => c.swapped || c.pct !== 100);
}

function describe(c) {
  const what = c.swapped ? `${c.slot.name} -> ${c.src.name}` : c.slot.name;
  return `${what}, ${c.hp} HP (${c.pct}% of ${c.src.spawnhealth})`;
}

function buildDehacked(changes) {
  const out = ['Patch File for DeHackEd v3.0', '',
    '# CozyDoom - generated by the CozyDoom WAD builder', ''];
  out.push(...changes.map(c => '#   ' + describe(c)));
  out.push('', 'Doom version = 19', 'Patch format = 6', '');

  const frames = [];         // extra frames: {num, sprite, frame, tics, next, action}
  let nextFrame = EXTRA_FRAME_BASE;

  // Copies a death sequence to fresh frames and puts A_BossDeath on its last
  // action-less frame (that is where the vanilla bosses have it too).
  function bossDeathCopy(start) {
    const chain = deathChain(start);
    if (!chain.length) return 0;
    const map = new Map(chain.map(i => [i, nextFrame++]));
    const copies = chain.map(i => ({ num: map.get(i), ...STATES[i],
      next: map.has(STATES[i].next) ? map.get(STATES[i].next) : STATES[i].next }));
    for (let k = copies.length - 1; k >= 0; k--) {
      if (!copies[k].action) { copies[k].action = 'BossDeath'; break; }
    }
    frames.push(...copies);
    return map.get(chain[0]);
  }

  for (const c of changes) {
    const { slot, src } = c;
    out.push(`Thing ${slot.index} (${slot.name})`);
    if (!c.swapped) {
      out.push(`Hit points = ${c.hp}`, '');
      continue;
    }
    const m = { ...src, doomednum: slot.doomednum, spawnhealth: c.hp };
    if (needsBossFix(slot, src)) {
      m.deathstate = bossDeathCopy(src.deathstate);
      if (src.xdeathstate) m.xdeathstate = bossDeathCopy(src.xdeathstate);
    }
    out.push(...DEH_FIELDS.map(([label, f]) => `${label} = ${m[f]}`));
    // MBF21 ports: take the new monster's behaviour bits, keep the slot's boss bits.
    const bits = [src.mbf21, slot.boss].filter(Boolean).join('+') || '0';
    out.push(`MBF21 Bits = ${bits}`, '');
  }

  for (const f of frames) {
    out.push(`Frame ${f.num}`, `Sprite number = ${f.sprite}`, `Sprite subnumber = ${f.frame}`,
      `Duration = ${f.tics}`, `Next frame = ${f.next}`, '');
  }
  const ptrs = frames.filter(f => f.action);
  if (ptrs.length) {
    out.push('[CODEPTR]', ...ptrs.map(f => `FRAME ${f.num} = ${f.action}`), '');
  }
  return out.join('\n');
}

function buildZScript(changes) {
  const out = ['version "4.0"', '', '// CozyDoom - generated by the CozyDoom WAD builder', ''];
  for (const c of changes) {
    const { slot, src } = c;
    out.push(`// ${describe(c)}`);
    out.push(`class CZ_${slot.cls} : ${src.cls} replaces ${slot.cls}`, '{', '\tDefault', '\t{');
    out.push(`\t\tHealth ${c.hp};`);
    // Keep the slot's own drop (DEHACKED does the same: drops depend on the slot).
    if (c.swapped && slot.drop !== src.drop) out.push(`\t\tDropItem "${slot.drop || 'None'}";`);
    out.push('\t}');
    if (needsBossFix(slot, src)) {
      out.push('', '\t// Keeps boss-level exits (e.g. MAP07) working with this replacement.',
        '\toverride void Die(Actor source, Actor inflictor, int dmgflags, Name MeansOfDeath)',
        '\t{', '\t\tSuper.Die(source, inflictor, dmgflags, MeansOfDeath);', '\t\tA_BossDeath();', '\t}');
    }
    out.push('}', '');
  }
  return out.join('\n');
}

function buildZMapinfo(changes) {
  return ['// CozyDoom: editor numbers -> replacement classes (GZDoom/UZDoom)', 'DoomEdNums', '{',
    ...changes.map(c => `\t${c.slot.doomednum} = "CZ_${c.slot.cls}"`), '}', ''].join('\n');
}

function toBytes(text) {
  const s = text.replace(/\r?\n/g, '\r\n');
  const b = new Uint8Array(s.length);
  for (let i = 0; i < s.length; i++) b[i] = s.charCodeAt(i) & 0x7f;
  return b;
}

// lumps: [[name, Uint8Array], ...] -> PWAD bytes
function writeWad(lumps) {
  const dataLen = lumps.reduce((n, [, d]) => n + d.length, 0);
  const buf = new Uint8Array(12 + dataLen + 16 * lumps.length);
  const dv = new DataView(buf.buffer);
  buf.set([0x50, 0x57, 0x41, 0x44], 0); // "PWAD"
  dv.setInt32(4, lumps.length, true);
  dv.setInt32(8, 12 + dataLen, true);
  let ofs = 12, dir = 12 + dataLen;
  for (const [name, data] of lumps) {
    buf.set(data, ofs);
    dv.setInt32(dir, ofs, true);
    dv.setInt32(dir + 4, data.length, true);
    for (let i = 0; i < 8; i++) buf[dir + 8 + i] = i < name.length ? name.charCodeAt(i) : 0;
    ofs += data.length;
    dir += 16;
  }
  return buf;
}

function buildLumps(choices) {
  const changes = activeChanges(choices);
  return {
    changes,
    DEHACKED: buildDehacked(changes),
    ZSCRIPT: buildZScript(changes),
    ZMAPINFO: buildZMapinfo(changes),
  };
}

function buildWad(choices) {
  const l = buildLumps(choices);
  return writeWad(['DEHACKED', 'ZSCRIPT', 'ZMAPINFO'].map(n => [n, toBytes(l[n])]));
}
